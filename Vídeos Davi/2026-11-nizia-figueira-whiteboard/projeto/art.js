// Biblioteca de desenhos (traço preto, poucos detalhes de cor). Origem dos personagens: entre os pés.
const S = (d, w = 5, c) => ({ d, w, c });
const F = (d, f) => ({ d, f, fo: true });
const dot = (x, y, r = 4.5) => S(`M${x},${y} l0.01,0`, r * 2);
const circ = (cx, cy, r) => `M${cx - r},${cy} a${r},${r} 0 1,0 ${2 * r},0 a${r},${r} 0 1,0 ${-2 * r},0`;
const ell = (cx, cy, rx, ry) => `M${cx - rx},${cy} a${rx},${ry} 0 1,0 ${2 * rx},0 a${rx},${ry} 0 1,0 ${-2 * rx},0`;

function face(cy, mood = 'neutral', look = 0) {
  const e = [];
  const ex = 16, ey = cy - 4;
  // sobrancelhas
  if (mood === 'sad') e.push(S(`M${-26},${ey - 14} Q${-16},${ey - 22} ${-8},${ey - 22}`, 4), S(`M26,${ey - 14} Q16,${ey - 22} 8,${ey - 22}`, 4));
  else if (mood === 'hope') e.push(S(`M${-26},${ey - 20} Q${-17},${ey - 27} ${-8},${ey - 21}`, 4), S(`M26,${ey - 20} Q17,${ey - 27} 8,${ey - 21}`, 4));
  else if (mood === 'doubt') e.push(S(`M${-26},${ey - 16} Q${-17},${ey - 20} ${-8},${ey - 17}`, 4), S(`M26,${ey - 26} Q17,${ey - 22} 8,${ey - 19}`, 4));
  else e.push(S(`M${-25},${ey - 17} Q${-16},${ey - 23} ${-7},${ey - 18}`, 4), S(`M25,${ey - 17} Q16,${ey - 23} 7,${ey - 18}`, 4));
  // olhos
  if (mood === 'closed') e.push(S(`M${-22},${ey} Q${-15},${ey + 6} ${-8},${ey}`, 4), S(`M22,${ey} Q15,${ey + 6} 8,${ey}`, 4));
  else e.push(dot(-ex + look, ey, 4.5), dot(ex + look, ey, 4.5));
  // nariz
  e.push(S(`M${2 + look},${cy + 2} Q${-5 + look},${cy + 16} ${4 + look},${cy + 18}`, 3.5));
  // boca
  const my = cy + 34;
  if (mood === 'sad') e.push(S(`M-11,${my + 3} Q0,${my - 6} 11,${my + 3}`, 4));
  else if (mood === 'smile' || mood === 'hope') e.push(S(`M-13,${my - 3} Q0,${my + 9} 13,${my - 3}`, 4));
  else if (mood === 'o') e.push(S(ell(0, my, 6, 8), 4));
  else if (mood === 'doubt') e.push(S(`M-10,${my} Q2,${my - 3} 12,${my - 5}`, 4));
  else e.push(S(`M-10,${my} Q0,${my + 2} 10,${my}`, 4));
  return e;
}

